#!/usr/bin/env python3
"""Build data/adjectives.js from the Notion Adjetivos snapshot kept by anki/notion_sync.py.

    python3 scripts/build_adjectives.py                     # default cache path
    python3 scripts/build_adjectives.py --cache path/to/notion_cache.json

Refresh the snapshot first with `python3 ../anki/notion_sync.py pull` (which also
runs this script). Stdlib only. Writes a classic <script> (window.ADJECTIVES = [...])
so the site also works when the page is opened straight from disk.
"""
import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_CACHE = ROOT.parent / "anki" / "data" / "notion_cache.json"
OUT = ROOT / "data" / "adjectives.js"

TYPES = {"Adjetivo I": "i", "Adjetivo Na": "na"}  # 'Adjetivo prenominal' (主な, 次の…) does not inflect

# Rows that are in the list but are not adjectives you conjugate on their own, keyed by Kanji.
SKIP = {
    "大きな",  # tagged Na, but it is a prenominal (連体詞): 大きだ does not exist; 大きい is drilled
    "難い",    # the suffix 〜にくい, not a word on its own
}


def hira(s):
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)


def log(msg):
    print(msg, file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", type=Path, default=DEFAULT_CACHE)
    args = ap.parse_args()

    rows = json.loads(args.cache.read_text(encoding="utf-8"))["decks"]["Adjetivos"]["rows"]

    adjs, seen, bad = [], set(), []
    for row in rows:
        t = TYPES.get(row.get("Tipo"))
        # Readings are sometimes spaced (けしき が いい) or doubled (いい / よい): keep the first.
        kana = re.sub(r"\s+", "", (row.get("Hiragana") or "").split("/")[0])
        kanji = re.sub(r"\s+", "", row.get("Kanji") or "") or kana
        if not t or not kana or kanji in SKIP:
            continue
        if not re.search(r"[\u3400-\u9fff]", kanji):
            kana = hira(kanji)  # kana-only words: ヘルシーな is read へるしーな, not the へるしいな in Notion
        end = "な" if t == "na" else "い"
        if not (hira(kanji).endswith(end) and kana.endswith(end)):  # キツイ is spelt in katakana
            bad.append(f"{kanji} {kana} ({row.get('Tipo')}): should end in {end}")
            continue
        if (kanji, kana) in seen:
            continue
        seen.add((kanji, kana))
        adjs.append({
            "k": kanji,
            "r": kana,
            "t": t,
            "es": (row.get("Español") or "").strip(),
            "ej": (row.get("Ejemplo") or "").strip(),
        })
    for b in bad:
        log(f"skip: {b}")

    adjs.sort(key=lambda a: a["r"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/build_adjectives.py from the Notion 'Adjetivos' database. Do not edit.\n"
        "window.ADJECTIVES = [\n"
        + ",\n".join(json.dumps(a, ensure_ascii=False) for a in adjs)
        + "\n];\n",
        encoding="utf-8",
    )
    n_i = sum(a["t"] == "i" for a in adjs)
    log(f"wrote {len(adjs)} adjectives ({n_i} い, {len(adjs) - n_i} な) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
